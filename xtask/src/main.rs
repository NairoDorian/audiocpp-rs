/// Number of parameters in a `(...)` list ("void" or empty = 0).
fn arity(params: &str) -> usize {
    let p = params.trim();
    if p.is_empty() || p == "void" {
        0
    } else {
        p.split(',').count()
    }
}

/// function name -> parameter count, from every `AUDIOCPP_API ... name(...)` declaration.
fn header_functions(header: &str) -> BTreeMap<String, usize> {
    let mut out = BTreeMap::new();
    let mut rest = header;
    while let Some(pos) = rest.find("AUDIOCPP_API ") {
        rest = &rest[pos + "AUDIOCPP_API ".len()..];
        let Some(open) = rest.find('(') else { break };
        let Some(close) = rest[open..].find(')') else { break };
        let head = &rest[..open];
        let name: String = head
            .trim_end()
            .chars()
            .rev()
            .take_while(|c| c.is_ascii_alphanumeric() || *c == '_')
            .collect::<String>()
            .chars()
            .rev()
            .collect();
        if name.starts_with("audiocpp_") {
            out.insert(name, arity(&rest[open + 1..open + close]));
        }
        rest = &rest[open + close..];
    }
    out
}

/// function name -> parameter count, from every `pub fn audiocpp_...(...)` in the bindings.
fn rust_functions(src: &str) -> BTreeMap<String, usize> {
    let mut out = BTreeMap::new();
    let mut rest = src;
    while let Some(pos) = rest.find("pub fn audiocpp_") {
        rest = &rest[pos + "pub fn ".len()..];
        let Some(open) = rest.find('(') else { break };
        let name = rest[..open].trim().to_string();
        // Parameters may contain `(` only inside an Option<unsafe extern fn(...)> type,
        // which no function parameter uses; count to the matching `)`.
        let Some(close) = rest[open..].find(')') else { break };
        let params = &rest[open + 1..open + close];
        let n = params.split(',').filter(|p| !p.trim().is_empty()).count();
        out.insert(name, n);
        rest = &rest[open + close..];
    }
    out
}

fn define(header: &str, name: &str) -> Option<u32> {
    header.lines().find_map(|l| {
        let mut it = l.split_whitespace();
        (it.next() == Some("#define") && it.next() == Some(name)).then(|| it.next()?.parse().ok())?
    })
}

fn rust_const(src: &str, name: &str) -> Option<u32> {
    let needle = format!("pub const {name}: u32 = ");
    let start = src.find(&needle)? + needle.len();
    src[start..].split(';').next()?.trim().parse().ok()
}

fn check_abi(update: bool) -> Result<bool, String> {
    let header_path = audio_cpp().join("include").join("audiocpp.h");
    let bindings_path = root().join("audiocpp-sys").join("src").join("lib.rs");
    let lock_path = root().join("audiocpp-sys").join("abi.lock");
    let header = fs::read_to_string(&header_path).map_err(|e| format!("{}: {e}", header_path.display()))?;
    let bindings = fs::read_to_string(&bindings_path).map_err(|e| format!("{}: {e}", bindings_path.display()))?;

    let mut ok = true;
    let c_fns = header_functions(&header);
    let rs_fns = rust_functions(&bindings);
    for (name, n) in &c_fns {
        match rs_fns.get(name) {
            None => {
                eprintln!("missing in bindings: {name} ({n} parameters)");
                ok = false;
            }
            Some(m) if m != n => {
                eprintln!("parameter count differs: {name}: header {n}, bindings {m}");
                ok = false;
            }
            _ => {}
        }
    }
    for name in rs_fns.keys().filter(|k| !c_fns.contains_key(*k)) {
        eprintln!("not in the header: {name}");
        ok = false;
    }
    let mut version = String::new();
    for part in ["MAJOR", "MINOR", "PATCH"] {
        let name = format!("AUDIOCPP_ABI_VERSION_{part}");
        let (c, r) = (define(&header, &name), rust_const(&bindings, &name));
        if c != r || c.is_none() {
            eprintln!("{name}: header {c:?}, bindings {r:?}");
            ok = false;
        }
        version.push_str(&format!("{}{}", if version.is_empty() { "" } else { "." }, c.unwrap_or(0)));
    }

    let digest = format!("{:x}", Sha256::digest(header.replace("\r\n", "\n").as_bytes()));
    let describe = git(&audio_cpp(), &["describe", "--tags", "--always", "--abbrev=8"]).unwrap_or_default();
    let lock = format!(
        "# Written by `cargo xtask check-abi --update` after the bindings were reviewed\n\
         # against this header. A different hash means the header changed: review\n\
         # audiocpp-sys/src/lib.rs, then update.\n\
         header = \"include/audiocpp.h\"\n\
         sha256 = \"{digest}\"\n\
         abi = \"{version}\"\n\
         reviewed-at = \"{describe}\"\n"
    );
    if update {
        if !ok {
            eprintln!("not updating abi.lock: fix the bindings first");
            return Ok(false);
        }
        fs::write(&lock_path, &lock).map_err(|e| format!("{}: {e}", lock_path.display()))?;
        println!("wrote {} (ABI {version}, {} functions)", lock_path.display(), c_fns.len());
        return Ok(true);
    }
    let recorded = fs::read_to_string(&lock_path).unwrap_or_default();
    if !recorded.contains(&format!("sha256 = \"{digest}\"")) {
        eprintln!("audiocpp.h changed since the bindings were last reviewed (abi.lock): review src/lib.rs, then run cargo xtask check-abi --update");
        ok = false;
    }
    if ok {
        println!("bindings match audiocpp.h: ABI {version}, {} functions ({describe})", c_fns.len());
    }
    Ok(ok)
}

// ---------------------------------------------------------------------------
// status
// ---------------------------------------------------------------------------
fn git(dir: &Path, args: &[&str]) -> Option<String> {
    let out = Command::new("git").arg("-C").arg(dir).args(args).output().ok()?;
    out.status.success().then(|| String::from_utf8_lossy(&out.stdout).trim().to_string())
}

fn is_release_tag(tag: &str) -> bool {
    let Some(v) = tag.strip_prefix('v') else { return false };
    let parts: Vec<&str> = v.split('.').collect();
    parts.len() == 3 && parts.iter().all(|p| !p.is_empty() && p.chars().all(|c| c.is_ascii_digit()))
}

fn status(fetch: bool) -> Result<bool, String> {
    let dir = audio_cpp();
    if fetch {
        println!("fetching audio.cpp ...");
        git(&dir, &["fetch", "origin", "--tags", "--prune", "--force"]).ok_or("git fetch failed")?;
    }
    let pin = git(&root(), &["ls-files", "-s", "--", "audiocpp-sys/audio.cpp"])
        .and_then(|l| l.split_whitespace().nth(1).map(str::to_string))
        .ok_or("audiocpp-sys/audio.cpp is not a submodule here")?;
    let head = git(&dir, &["rev-parse", "HEAD"]).ok_or("audio.cpp is not checked out")?;
    let describe = |rev: &str| git(&dir, &["describe", "--tags", "--always", "--abbrev=8", rev]).unwrap_or_default();
    let count = |a: &str, b: &str| {
        git(&dir, &["rev-list", "--left-right", "--count", &format!("{a}...{b}")])
            .map(|s| s.split_whitespace().map(str::to_string).collect::<Vec<_>>())
            .filter(|v| v.len() == 2)
            .map(|v| format!("+{} new / {} only in the pin", v[1], v[0]))
            .unwrap_or_default()
    };
    println!("audio.cpp pin   {}  {}", &pin[..8], describe(&pin));
    println!("checkout        {}  {}", &head[..8], if head == pin { "= pin" } else { "DIFFERS from the pin" });
    let tags = git(&dir, &["tag", "-l", "v*", "--sort=-v:refname"]).unwrap_or_default();
    if let Some(latest) = tags.lines().find(|t| is_release_tag(t)) {
        let sha = git(&dir, &["rev-parse", &format!("{latest}^{{commit}}")]).unwrap_or_default();
        println!(
            "release lane    {}  {latest}  {}",
            &sha[..8.min(sha.len())],
            if sha == pin { "same as the pin".into() } else { count(&pin, &sha) }
        );
    }
    if let Some(main) = git(&dir, &["rev-parse", "refs/remotes/origin/main"]) {
        println!("main lane       {}  origin/main  {}", &main[..8], count(&pin, &main));
    } else {
        println!("main lane       unknown (run: cargo xtask status --fetch)");
    }
    Ok(true)
}
