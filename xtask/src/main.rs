/// (target, aliases) for every `audiocpp_add_model(<target> ...)` block.
fn model_targets() -> Result<Vec<(String, Vec<String>)>, String> {
    let path = audio_cpp().join("CMakeLists.txt");
    let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    let mut out: Vec<(String, Vec<String>)> = Vec::new();
    for line in text.lines() {
        if let Some(rest) = line.strip_prefix("audiocpp_add_model(") {
            let name: String = rest.chars().take_while(|c| c.is_ascii_alphanumeric() || *c == '_').collect();
            if !name.is_empty() {
                out.push((name, Vec::new()));
            }
        } else if let Some(rest) = line.trim_start().strip_prefix("ALIASES") {
            if line.starts_with(char::is_whitespace) {
                if let Some(last) = out.last_mut() {
                    last.1.extend(rest.split_whitespace().map(str::to_string));
                }
            }
        }
    }
    if out.is_empty() {
        return Err(format!("no audiocpp_add_model(...) found in {}", path.display()));
    }
    out.sort();
    Ok(out)
}

fn replace_block(text: &str, body: &str) -> Result<String, String> {
    let start = text.find(BEGIN).ok_or("missing BEGIN marker")?;
    let end = text.find(END).ok_or("missing END marker")?;
    Ok(format!("{}{}\n{}{}", &text[..start], BEGIN, body, &text[end..]))
}

fn features(check: bool) -> Result<bool, String> {
    let targets = model_targets()?;
    let sys_body: String = targets.iter().map(|(t, _)| format!("model-{t} = []\n")).collect();
    let safe_body: String =
        targets.iter().map(|(t, _)| format!("model-{t} = [\"audiocpp-sys/model-{t}\"]\n")).collect();
    let mut doc = String::from(
        "# Model features\n\n> Generated by `cargo xtask features` from the pinned audio.cpp's `CMakeLists.txt`. Do not edit.\n\n\
         One Cargo feature per audio.cpp model target. Enable a feature on `audiocpp` (or `audiocpp-sys`) to compile \
         that family into the library; no model feature builds the core runtime only. Aliases are the other names \
         audio.cpp accepts for the same target (for `AUDIOCPP_MODELS`).\n\n",
    );
    doc.push_str(&format!("{} targets.\n\n| Feature | Aliases |\n|---|---|\n", targets.len()));
    for (t, aliases) in &targets {
        doc.push_str(&format!(
            "| `model-{t}` | {} |\n",
            aliases.iter().map(|a| format!("`{a}`")).collect::<Vec<_>>().join(" ")
        ));
    }

    let files = [
        (root().join("audiocpp-sys").join("Cargo.toml"), Some(sys_body)),
        (root().join("audiocpp").join("Cargo.toml"), Some(safe_body)),
        (root().join("docs").join("model-features.md"), None),
    ];
    let mut fresh = true;
    for (path, body) in files {
        let current = fs::read_to_string(&path).unwrap_or_default();
        let wanted = match body {
            Some(body) => replace_block(&current, &body).map_err(|e| format!("{}: {e}", path.display()))?,
            None => doc.clone(),
        };
        if current != wanted {
            if check {
                eprintln!("stale: {}", path.display());
                fresh = false;
            } else {
                fs::write(&path, wanted).map_err(|e| format!("{}: {e}", path.display()))?;
                println!("wrote {}", path.display());
            }
        }
    }
    if check && fresh {
        println!("model features match audio.cpp ({} targets)", targets.len());
    } else if !check {
        println!("{} model targets", targets.len());
    }
    Ok(fresh || !check)
}

