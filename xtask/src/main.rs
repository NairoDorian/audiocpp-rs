//! Repository automation for audiocpp-rs.
//!
//!   cargo xtask features [--check]   regenerate the model-<target> features of both
//!                                    crates (and docs/model-features.md) from the
//!                                    pinned audio.cpp's CMakeLists.txt
//!   cargo xtask check-abi [--update] prove audiocpp-sys/src/lib.rs against the pinned
//!                                    include/audiocpp.h: every function (name and
//!                                    parameter count), the ABI version, and the header
//!                                    hash recorded in audiocpp-sys/abi.lock
//!   cargo xtask status [--fetch]     the audio.cpp pin against its release and main lanes
//!
//! Every --check / check-abi exits 1 when something is stale, so CI can run them.

use sha2::{Digest, Sha256};
use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

const BEGIN: &str = "# BEGIN GENERATED MODEL FEATURES (cargo xtask features)";
const END: &str = "# END GENERATED MODEL FEATURES";

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).parent().expect("workspace root").to_path_buf()
}

fn audio_cpp() -> PathBuf {
    root().join("audiocpp-sys").join("audio.cpp")
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let flag = |f: &str| args.iter().any(|a| a == f);
    let result = match args.first().map(String::as_str) {
        Some("features") => features(flag("--check")),
        Some("check-abi") => check_abi(flag("--update")),
        Some("status") => status(flag("--fetch")),
        _ => {
            eprintln!("usage: cargo xtask <features [--check] | check-abi [--update] | status [--fetch]>");
            return ExitCode::from(2);
        }
    };
    match result {
        Ok(true) => ExitCode::SUCCESS,
        Ok(false) => ExitCode::FAILURE,
        Err(e) => {
            eprintln!("xtask: {e}");
            ExitCode::FAILURE
        }
    }
}

